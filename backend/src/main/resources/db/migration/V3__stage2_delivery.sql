-- V3__stage2_delivery.sql
-- Stage 2 delivery workflow: item statuses, done/delivered timestamps, and delivery overrides

-- Add status and completion timestamps to order_item
ALTER TABLE order_item
    ADD COLUMN status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    ADD COLUMN done_at TIMESTAMPTZ,
    ADD COLUMN delivered_at TIMESTAMPTZ;

-- Delivery override table: records when an item was handed over despite pending payment balance
CREATE TABLE delivery_override (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id BIGINT NOT NULL REFERENCES order_item(id),
    balance_at_time NUMERIC(10, 2) NOT NULL,
    reason TEXT NOT NULL,
    overridden_by BIGINT NOT NULL REFERENCES app_user(id)
);

-- Foreign key indexes for delivery_override
CREATE INDEX idx_delivery_override_order_item_id ON delivery_override(order_item_id);
CREATE INDEX idx_delivery_override_overridden_by ON delivery_override(overridden_by);
