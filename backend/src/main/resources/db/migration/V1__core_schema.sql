-- V1__core_schema.sql
-- Core schema for Geetanjali tailor shop management system

-- 1. Shop table: Store information for the tailor shop
CREATE TABLE shop (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

-- 2. App User table: Staff members (Owner, Tailors)
CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id BIGINT NOT NULL REFERENCES shop(id),
    full_name VARCHAR(255) NOT NULL,
    mobile VARCHAR(20) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL
);

-- 3. Customer table: Tailor shop customers
CREATE TABLE customer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    mobile VARCHAR(20) NOT NULL UNIQUE
);

-- 4. Garment table: Types of clothing (e.g. Shirt, Pant, Kurta, Blouse)
CREATE TABLE garment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    sort_order INT NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

-- 5. Garment Field table: Dynamic measurement fields configured for each garment
CREATE TABLE garment_field (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    garment_id BIGINT NOT NULL REFERENCES garment(id),
    label VARCHAR(100) NOT NULL,
    unit VARCHAR(20) NOT NULL DEFAULT 'inch',
    sort_order INT NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

-- 6. Measurement table: A recording session of measurements for a customer and garment
CREATE TABLE measurement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customer(id),
    garment_id BIGINT NOT NULL REFERENCES garment(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 7. Measurement Value table: Actual numeric measurement values for each field
CREATE TABLE measurement_value (
    measurement_id BIGINT NOT NULL REFERENCES measurement(id),
    field_id BIGINT NOT NULL REFERENCES garment_field(id),
    value NUMERIC(6, 2) NOT NULL,
    PRIMARY KEY (measurement_id, field_id)
);

-- Sequence for human-readable order numbers (starting at 1001)
CREATE SEQUENCE order_no_seq START WITH 1001 INCREMENT BY 1;

-- 8. Customer Order table: Top-level order placing by a customer
CREATE TABLE customer_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no BIGINT NOT NULL UNIQUE DEFAULT nextval('order_no_seq'),
    customer_id BIGINT NOT NULL REFERENCES customer(id),
    created_by BIGINT NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 9. Order Item table: Each individual stitched item in an order
CREATE TABLE order_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES customer_order(id),
    garment_id BIGINT NOT NULL REFERENCES garment(id),
    measurement_id BIGINT REFERENCES measurement(id),
    notes TEXT,
    price NUMERIC(10, 2) NOT NULL,
    delivery_date DATE NOT NULL
);

-- 10. Item Photo table: Cloth samples or design photos
CREATE TABLE item_photo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id BIGINT NOT NULL REFERENCES order_item(id),
    url VARCHAR(500) NOT NULL,
    public_id VARCHAR(255)
);

-- 11. Payment table: Payments recorded for an order
CREATE TABLE payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES customer_order(id),
    amount NUMERIC(10, 2) NOT NULL,
    mode VARCHAR(50) NOT NULL,
    paid_on DATE NOT NULL DEFAULT CURRENT_DATE
);

-- -------------------------------------------------------------
-- Indexes on all foreign key columns to ensure fast JOIN queries
-- -------------------------------------------------------------
CREATE INDEX idx_app_user_shop_id ON app_user(shop_id);
CREATE INDEX idx_garment_field_garment_id ON garment_field(garment_id);
CREATE INDEX idx_measurement_customer_id ON measurement(customer_id);
CREATE INDEX idx_measurement_garment_id ON measurement(garment_id);
CREATE INDEX idx_measurement_value_field_id ON measurement_value(field_id);
CREATE INDEX idx_customer_order_customer_id ON customer_order(customer_id);
CREATE INDEX idx_customer_order_created_by ON customer_order(created_by);
CREATE INDEX idx_order_item_order_id ON order_item(order_id);
CREATE INDEX idx_order_item_garment_id ON order_item(garment_id);
CREATE INDEX idx_order_item_measurement_id ON order_item(measurement_id);
CREATE INDEX idx_item_photo_order_item_id ON item_photo(order_item_id);
CREATE INDEX idx_payment_order_id ON payment(order_id);
