import static org.mockito.Mockito.*;

// MeasurementServiceTest: Unit tests verifying the measurement snapshot engine.
// Specifically tests:
// 1. Prefill logic: returns newest snapshot values or empty.
// 2. Snapshot deduplication: saving identical numbers (e.g. 38.0 vs 38.00) reuses the existing snapshot.
// 3. Snapshot creation: changing even one number creates a new snapshot.
// 4. Latest per garment: loops active garments and attaches newest measurements.
@ExtendWith(MockitoExtension.class)
class MeasurementServiceTest {

    @Mock
    private MeasurementRepository measurementRepository;

    @Mock
    private MeasurementValueRepository measurementValueRepository;

    @Mock
    private GarmentRepository garmentRepository;

    @Mock
    private GarmentFieldRepository garmentFieldRepository;

    @Mock
    private CustomerRepository customerRepository;

    private Clock clock;
    private MeasurementService measurementService;

    private Customer customer;
    private Garment shirt;
    private Garment pant;
    private GarmentField lengthField;
    private GarmentField chestField;

    @BeforeEach
    void setUp() {
        clock = Clock.fixed(Instant.parse("2026-10-13T10:00:00Z"), ZoneId.of("Asia/Kolkata"));
        measurementService = new MeasurementService(
                measurementRepository,
                measurementValueRepository,
                garmentRepository,
                garmentFieldRepository,
                customerRepository,
                clock
        );

        customer = new Customer("Ramesh Patel", "9876543210");
        shirt = new Garment("Shirt", 1, true);
        pant = new Garment("Pant", 2, true);

        lengthField = new GarmentField(shirt, "Length", "inch", 1, true);
        chestField = new GarmentField(shirt, "Chest", "inch", 2, true);

        // Reflection/hack-free setup of IDs on mock entities
        // Since IDs are generated by DB, we create dummy records with getters
        setEntityId(customer, 10L);
        setEntityId(shirt, 1L);
        setEntityId(pant, 2L);
        setEntityId(lengthField, 101L);
        setEntityId(chestField, 102L);
    }

    private void setEntityId(Object entity, Long id) {
        try {
            java.lang.reflect.Field field = entity.getClass().getDeclaredField("id");
            field.setAccessible(true);
            field.set(entity, id);
        } catch (Exception e) {
            throw new RuntimeException(e);
        }
    }

    // =========================================================================
    // 1. PREFILL TESTS
    // =========================================================================

    @Test
    @DisplayName("Prefill returns empty Optional when customer has no measurements for garment")
    void testGetPrefill_returnsEmptyWhenNoSnapshot() {
        when(measurementRepository.findFirstByCustomerIdAndGarmentIdOrderByCreatedAtDesc(10L, 1L))
                .thenReturn(Optional.empty());

        Optional<MeasurementPrefill> prefill = measurementService.getPrefill(10L, 1L);

        assertTrue(prefill.isEmpty(), "Prefill must be empty when no snapshot exists");
    }

    @Test
    @DisplayName("Prefill returns values map and date when customer has a snapshot")
    void testGetPrefill_returnsValuesAndDateWhenSnapshotExists() {
        Measurement snapshot = new Measurement(customer, shirt, clock.instant());
        setEntityId(snapshot, 55L);

        MeasurementValue val1 = new MeasurementValue(snapshot, lengthField, new BigDecimal("30.0"));
        MeasurementValue val2 = new MeasurementValue(snapshot, chestField, new BigDecimal("38.5"));

        when(measurementRepository.findFirstByCustomerIdAndGarmentIdOrderByCreatedAtDesc(10L, 1L))
                .thenReturn(Optional.of(snapshot));
        when(measurementValueRepository.findByMeasurementId(55L))
                .thenReturn(List.of(val1, val2));

        Optional<MeasurementPrefill> prefillOpt = measurementService.getPrefill(10L, 1L);

        assertTrue(prefillOpt.isPresent(), "Prefill must be present");
        MeasurementPrefill prefill = prefillOpt.get();
        assertEquals(55L, prefill.measurementId());
        assertEquals(2, prefill.values().size());
        assertEquals(new BigDecimal("30.0"), prefill.values().get(101L));
        assertEquals(new BigDecimal("38.5"), prefill.values().get(102L));
        assertNotNull(prefill.date());
    }

    // =========================================================================
    // 2. SAVE SNAPSHOT TESTS (Deduplication vs Creation)
    // =========================================================================

    @Test
    @DisplayName("Saving first time creates a new snapshot and saves each measurement value")
    void testSaveSnapshot_firstTimeCreatesNewSnapshot() {
        when(measurementRepository.findFirstByCustomerIdAndGarmentIdOrderByCreatedAtDesc(10L, 1L))
                .thenReturn(Optional.empty());

        Measurement createdSnapshot = new Measurement(customer, shirt, clock.instant());
        setEntityId(createdSnapshot, 100L);
        when(measurementRepository.save(any(Measurement.class))).thenReturn(createdSnapshot);

        when(garmentFieldRepository.findById(101L)).thenReturn(Optional.of(lengthField));
        when(garmentFieldRepository.findById(102L)).thenReturn(Optional.of(chestField));

        Map<Long, BigDecimal> submitted = new LinkedHashMap<>();
        submitted.put(101L, new BigDecimal("30.0"));
        submitted.put(102L, new BigDecimal("38.0"));

        Measurement result = measurementService.saveSnapshot(customer, shirt, submitted);

        assertNotNull(result);
        assertEquals(100L, result.getId());
        verify(measurementRepository, times(1)).save(any(Measurement.class));
        verify(measurementValueRepository, times(2)).save(any(MeasurementValue.class));
    }

    @Test
    @DisplayName("Saving the EXACT same numbers twice reuses the existing snapshot (BigDecimal compareTo rule)")
    void testSaveSnapshot_savingSameNumbersTwiceReusesExistingSnapshot() {
        // Arrange existing snapshot with values 30.0 and 38.0
        Measurement existingSnapshot = new Measurement(customer, shirt, clock.instant());
        setEntityId(existingSnapshot, 100L);

        MeasurementValue val1 = new MeasurementValue(existingSnapshot, lengthField, new BigDecimal("30.0"));
        MeasurementValue val2 = new MeasurementValue(existingSnapshot, chestField, new BigDecimal("38.0"));

        when(measurementRepository.findFirstByCustomerIdAndGarmentIdOrderByCreatedAtDesc(10L, 1L))
                .thenReturn(Optional.of(existingSnapshot));
        when(measurementValueRepository.findByMeasurementId(100L))
                .thenReturn(List.of(val1, val2));

        // Submit numbers with different scale: 30.00 and 38.00 (mathematically identical)
        Map<Long, BigDecimal> submitted = new LinkedHashMap<>();
        submitted.put(101L, new BigDecimal("30.00"));
        submitted.put(102L, new BigDecimal("38.00"));

        // Act
        Measurement result = measurementService.saveSnapshot(customer, shirt, submitted);

        // Assert: reuses existing snapshot, does NOT insert a new measurement
        assertEquals(100L, result.getId());
        verify(measurementRepository, never()).save(any(Measurement.class));
        verify(measurementValueRepository, never()).save(any(MeasurementValue.class));
    }

    @Test
    @DisplayName("Changing ONE number creates a SECOND snapshot")
    void testSaveSnapshot_changingOneNumberCreatesNewSnapshot() {
        // Arrange existing snapshot with Chest = 38.0
        Measurement existingSnapshot = new Measurement(customer, shirt, clock.instant());
        setEntityId(existingSnapshot, 100L);

        MeasurementValue val1 = new MeasurementValue(existingSnapshot, lengthField, new BigDecimal("30.0"));
        MeasurementValue val2 = new MeasurementValue(existingSnapshot, chestField, new BigDecimal("38.0"));

        when(measurementRepository.findFirstByCustomerIdAndGarmentIdOrderByCreatedAtDesc(10L, 1L))
                .thenReturn(Optional.of(existingSnapshot));
        when(measurementValueRepository.findByMeasurementId(100L))
                .thenReturn(List.of(val1, val2));

        // New snapshot mock
        Measurement secondSnapshot = new Measurement(customer, shirt, clock.instant());
        setEntityId(secondSnapshot, 101L);
        when(measurementRepository.save(any(Measurement.class))).thenReturn(secondSnapshot);
        when(garmentFieldRepository.findById(101L)).thenReturn(Optional.of(lengthField));
        when(garmentFieldRepository.findById(102L)).thenReturn(Optional.of(chestField));

        // Submit modified numbers: Chest changed from 38.0 to 39.5
        Map<Long, BigDecimal> submitted = new LinkedHashMap<>();
        submitted.put(101L, new BigDecimal("30.0"));
        submitted.put(102L, new BigDecimal("39.5"));

        // Act
        Measurement result = measurementService.saveSnapshot(customer, shirt, submitted);

        // Assert: returns second snapshot, saves new measurement and values
        assertEquals(101L, result.getId());
        verify(measurementRepository, times(1)).save(any(Measurement.class));
        verify(measurementValueRepository, times(2)).save(any(MeasurementValue.class));
    }

    @Test
    @DisplayName("Adding a new field or removing a field creates a new snapshot")
    void testSaveSnapshot_addingOrRemovingFieldCreatesNewSnapshot() {
        Measurement existingSnapshot = new Measurement(customer, shirt, clock.instant());
        setEntityId(existingSnapshot, 100L);

        MeasurementValue val1 = new MeasurementValue(existingSnapshot, lengthField, new BigDecimal("30.0"));

        when(measurementRepository.findFirstByCustomerIdAndGarmentIdOrderByCreatedAtDesc(10L, 1L))
                .thenReturn(Optional.of(existingSnapshot));
        when(measurementValueRepository.findByMeasurementId(100L))
                .thenReturn(List.of(val1));

        Measurement secondSnapshot = new Measurement(customer, shirt, clock.instant());
        setEntityId(secondSnapshot, 102L);
        when(measurementRepository.save(any(Measurement.class))).thenReturn(secondSnapshot);
        when(garmentFieldRepository.findById(101L)).thenReturn(Optional.of(lengthField));
        when(garmentFieldRepository.findById(102L)).thenReturn(Optional.of(chestField));

        // Submit two fields instead of one (Chest added)
        Map<Long, BigDecimal> submitted = new LinkedHashMap<>();
        submitted.put(101L, new BigDecimal("30.0"));
        submitted.put(102L, new BigDecimal("38.0"));

        Measurement result = measurementService.saveSnapshot(customer, shirt, submitted);

        assertEquals(102L, result.getId());
        verify(measurementRepository, times(1)).save(any(Measurement.class));
    }

    // =========================================================================
    // 3. LATEST PER GARMENT TESTS
    // =========================================================================

    @Test
    @DisplayName("getLatestPerGarment returns active garments in order with snapshots attached")
    void testGetLatestPerGarment_returnsActiveGarmentsWithSnapshots() {
        when(garmentRepository.findByActiveTrueOrderBySortOrderAsc())
                .thenReturn(List.of(shirt, pant));

        // Shirt has snapshot #100
        Measurement shirtSnapshot = new Measurement(customer, shirt, clock.instant());
        setEntityId(shirtSnapshot, 100L);
        MeasurementValue shirtVal = new MeasurementValue(shirtSnapshot, chestField, new BigDecimal("38.0"));

        when(measurementRepository.findFirstByCustomerIdAndGarmentIdOrderByCreatedAtDesc(10L, 1L))
                .thenReturn(Optional.of(shirtSnapshot));
        when(measurementValueRepository.findByMeasurementId(100L))
                .thenReturn(List.of(shirtVal));

        // Pant has no snapshot
        when(measurementRepository.findFirstByCustomerIdAndGarmentIdOrderByCreatedAtDesc(10L, 2L))
                .thenReturn(Optional.empty());

        List<GarmentLatestMeasurement> list = measurementService.getLatestPerGarment(customer);

        assertEquals(2, list.size());

        // First is Shirt
        GarmentLatestMeasurement first = list.get(0);
        assertEquals("Shirt", first.garment().getName());
        assertTrue(first.hasMeasurement());
        assertEquals(100L, first.measurement().getId());
        assertEquals(1, first.values().size());

        // Second is Pant
        GarmentLatestMeasurement second = list.get(1);
        assertEquals("Pant", second.garment().getName());
        assertFalse(second.hasMeasurement());
        assertNull(second.measurement());
        assertTrue(second.values().isEmpty());
    }
}
